// ===== USUARIO =====
export async function updateUsuario(
  clienteId: number,
  usuarioId: number,
  patch: {
    nome?: string | null;
    email?: string | null;
    telefone?: string | null;
    isActive?: boolean;
    crmId?: string | null;
    role?: "owner" | "vendedor";
  },
) {
  const vendedores = await loadVendedores(clienteId);

  // Unicidade de e-mail dentro do tenant.
  // Compara o novo e-mail (lowercase) contra todos os outros vendedores;
  // permite manter o mesmo e-mail do próprio registro.
  if (patch.email !== undefined && patch.email !== null) {
    const novoEmail = patch.email.trim().toLowerCase();
    if (novoEmail) {
      const conflito = vendedores.some(
        (v) => v.id !== usuarioId && (v.email ?? "").toLowerCase() === novoEmail,
      );
      if (conflito) {
        throw new Error(
          "Esse e-mail já está em uso por outro usuário deste tenant.",
        );
      }
    }
  }

  const next = vendedores.map((v) => {
    if (v.id !== usuarioId) return v;
    return {
      ...v,
      nome: patch.nome === undefined ? v.nome : patch.nome,
      email:
        patch.email === undefined
          ? v.email
          : patch.email
            ? patch.email.trim().toLowerCase()
            : null,
      telefone: patch.telefone === undefined ? v.telefone : patch.telefone,
      is_active: patch.isActive === undefined ? v.is_active : patch.isActive,
      crm_id: patch.crmId === undefined ? v.crm_id : patch.crmId,
      role: patch.role === undefined ? v.role : patch.role,
    };
  });
  await saveVendedores(clienteId, next);
  await syncLeadsVendedorSnapshot(clienteId, usuarioId);
}

// Edit inline por célula da tabela /usuarios.
// Aceita campos texto (nome, email, telefone, crmId) e role (select).
export async function updateUsuarioField(
  clienteId: number,
  usuarioId: number,
  field: "nome" | "email" | "telefone" | "crmId" | "role",
  value: string,
) {
  const v = value.trim();
  const patch: Parameters<typeof updateUsuario>[2] = {};
  if (field === "nome") patch.nome = v || null;
  else if (field === "email") patch.email = v || null;
  else if (field === "telefone") patch.telefone = v || null;
  else if (field === "crmId") patch.crmId = v || null;
  else if (field === "role") {
    if (v !== "owner" && v !== "vendedor") {
      throw new Error("Nível inválido. Use 'owner' ou 'vendedor'.");
    }
    patch.role = v;
  }
  await updateUsuario(clienteId, usuarioId, patch);
}

