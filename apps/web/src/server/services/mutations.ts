async function loadVendedores(clienteId: number): Promise<Vendedor[]> {
  const c = await db.query.clientes.findFirst({
    where: eq(clientes.id, clienteId),
  });
  return Array.isArray(c?.vendedores) ? (c.vendedores as Vendedor[]) : [];
}

async function saveVendedores(clienteId: number, vendedores: Vendedor[]) {
  await db
    .update(clientes)
    .set({ vendedores: vendedores as never })
    .where(eq(clientes.id, clienteId));
}

function nextVendedorId(vendedores: Vendedor[]): number {
  // ID baseado em timestamp ms — colisão entre cadastros simultâneos
  // exige sub-milissegundo, praticamente impossível em produção. Mantém
  // ordem cronológica e dispensa lock no jsonb. Acrescenta jitter de
  // 0–999 pra cobrir o caso raro de 2 chamadas no mesmo ms.
  let candidate = Date.now() * 1000 + Math.floor(Math.random() * 1000);
  const taken = new Set(vendedores.map((v) => v.id));
  while (taken.has(candidate)) candidate += 1;
  return candidate;
}

// ===== CLIENTE =====
export async function deleteCliente(
  clienteId: number,
  { skipChecks = false }: { skipChecks?: boolean } = {},
): Promise<{
  leadsRemovidos: number;
  agendamentosRemovidos: number;
  agentesRemovidos: number;
  automacoesRemovidas: number;
}> {
  // Bloqueio: não permite remover superadmin (Looper).
  if (!skipChecks) {
    const c = await db
      .select({ isSuperadmin: clientes.isSuperadmin })
      .from(clientes)
      .where(eq(clientes.id, clienteId))
      .limit(1);
    if (c[0]?.isSuperadmin === true) {
      throw new Error(
        "Cliente superadmin (Looper) não pode ser removido pela UI.",
      );
    }
  }

  // Cascade manual — não há FK formal porque vendedor virou jsonb.
  // Remove leads + agendamentos + agentes desse cliente.
  // Ordem importa: agendamentos referenciam leads (lead_id).
  const leadsDoCliente = await db
    .select({ id: leads.id })
    .from(leads)
    .where(eq(leads.clienteId, clienteId));
  const leadIds = leadsDoCliente.map((l) => l.id);

  let agendamentosRemovidos = 0;
  if (leadIds.length > 0) {
    const r = await db
      .delete(agendamentos)
      .where(inArray(agendamentos.leadId, leadIds))
      .returning({ id: agendamentos.id });
    agendamentosRemovidos = r.length;
  }
  const rLeads = await db
    .delete(leads)
    .where(eq(leads.clienteId, clienteId))
    .returning({ id: leads.id });
  const rAgentes = await db
    .delete(agentes)
    .where(eq(agentes.clienteId, clienteId))
    .returning({ id: agentes.id });

  // Conta instâncias de automações antes do delete cascata (FK
  // ON DELETE CASCADE em cliente_automacoes.cliente_id remove
  // automaticamente — só precisamos contar pra reportar no retorno).
  // Catálogo (`automacoes`) permanece intacto.
  const autosDoCliente = await db
    .select({ id: clientesAutomacoes.id })
    .from(clientesAutomacoes)
    .where(eq(clientesAutomacoes.clienteId, clienteId));
  const automacoesRemovidas = autosDoCliente.length;

  await db.delete(clientes).where(eq(clientes.id, clienteId));

  return {
    leadsRemovidos: rLeads.length,
    agendamentosRemovidos,
    agentesRemovidos: rAgentes.length,
    automacoesRemovidas,
  };
}

export async function createCliente(data: {
  nome: string;
  email: string;
  senha: string;
  crmTenant: string;
  telefone?: string | null;
  apiToken?: string | null;
  apiInstanciaNome?: string | null;
  apiBaseUrl?: string | null;
  crmToken?: string | null;
  crmOrigemId?: string | null;
  isSuperadmin?: boolean;
} & Record<string, unknown>): Promise<number> {
  const emailLower = data.email.trim().toLowerCase();
  const tenant = data.crmTenant.trim().toLowerCase();
  if (!emailLower) throw new Error("E-mail é obrigatório.");
  if (!tenant) throw new Error("Subdomínio (crm_tenant) é obrigatório.");
  if (data.senha.length < 6) {
    throw new Error("Senha deve ter ao menos 6 caracteres.");
  }

  // Unicidade de tenant — login e roteamento são por subdomínio.
  const existing = await db
    .select({ id: clientes.id })
    .from(clientes)
    .where(eq(clientes.crmTenant, tenant))
    .limit(1);
  if (existing.length > 0) {
    throw new Error(`Subdomínio "${tenant}" já está em uso.`);
  }

  const senhaHash = await bcrypt.hash(data.senha, 10);

  // is_superadmin tem CHECK constraint no banco (só permitido para
  // tenant=looper). Para outros, sempre false.
  const isSuperadmin =
    tenant === "looper" ? data.isSuperadmin === true : false;

  // `clientes.id` é GENERATED BY DEFAULT AS IDENTITY no banco.
  // Postgres gera o id; usamos RETURNING pra recuperar.
  const inserted = await db
    .insert(clientes)
    .values({
      nome: data.nome.trim() || null,
      email: emailLower,
      senha: senhaHash,
      telefone: data.telefone?.trim() || null,
      crmTenant: tenant,
      apiToken: data.apiToken?.trim() || null,
      apiInstanciaNome: data.apiInstanciaNome?.trim() || null,
      apiBaseUrl: data.apiBaseUrl?.trim() || null,
      crmToken: data.crmToken?.trim() || null,
      crmOrigemId: data.crmOrigemId?.trim() || null,
      // Estrutura completa dos 9 slots (slug + tipo preenchidos, nome e
      // id vazios). Admin completa depois via aba CRM ("Buscar do CRM"
      // ou manualmente).
      crmStatusColunas: defaultCrmStatusColunas(),
      isSuperadmin,
      isActive: true,
      // Lojas e vendedores começam com 1 item placeholder pra ancorar o
      // shape canonical no jsonb. Todos os campos presentes com valores
      // vazios — nada disso é lido pela UI até o admin preencher de
      // verdade. Filtros de listagem ignoram itens "vazios" por
      // checagem de campo-chave (loja sem nome, vendedor sem email).
      lojas: [emptyLoja()],
      vendedores: [emptyVendedor()],
    })
    .returning({ id: clientes.id });
  if (!inserted[0]) throw new Error("Insert de cliente não retornou id.");
  const id = inserted[0].id;

  return id;
}

export async function updateCliente(
  clienteId: number,
  patch: {
    nome?: string | null;
    email?: string | null;
    telefone?: string | null;
    apiToken?: string | null;
    apiInstanciaNome?: string | null;
    apiBaseUrl?: string | null;
    crmTenant?: string | null;
    crmToken?: string | null;
    crmOrigemId?: string | null;
    crmStatusColunas?:
      | Array<{
          nome: string;
          id: string;
          slug: string;
          tipo: "inicial" | "qualificacao" | "desqualificacao";
          notUsed?: boolean;
        }>
      | null;
  },
) {
  // Strip undefined — drizzle inclui undefined no SET, sobrescrevendo com NULL.
  const cleaned: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(patch)) {
    if (v !== undefined) cleaned[k] = v;
  }
  if (Object.keys(cleaned).length === 0) return;
  await db
    .update(clientes)
    .set(cleaned as never)
    .where(eq(clientes.id, clienteId));
}

