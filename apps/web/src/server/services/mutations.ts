export async function removeUsuario(
  clienteId: number,
  usuarioId: number,
  options: { transferToId?: number | null } = {},
) {
  const vendedores = await loadVendedores(clienteId);
  const next = vendedores.filter((v) => v.id !== usuarioId);
  if (next.length === vendedores.length) {
    throw new Error("Usuário não encontrado.");
  }

  // Reatribuição de leads do vendedor removido
  if (options.transferToId !== undefined) {
    if (options.transferToId === null) {
      // Liberar (vendedor_id = null) — vão pra fila de não-atribuídos
      await db
        .update(leads)
        .set({ vendedorId: null, vendedor: null })
        .where(
          and(
            eq(leads.clienteId, clienteId),
            eq(leads.vendedorId, usuarioId),
          ),
        );
    } else {
      // Confere se o destino existe na lista atual de vendedores (após remoção)
      const destino = next.find((v) => v.id === options.transferToId);
      if (!destino) {
        throw new Error("Vendedor de destino não encontrado.");
      }
      const snapshot = vendedorSnapshot(destino);
      await db
        .update(leads)
        .set({ vendedorId: options.transferToId, vendedor: snapshot })
        .where(
          and(
            eq(leads.clienteId, clienteId),
            eq(leads.vendedorId, usuarioId),
          ),
        );
    }
  }

  await saveVendedores(clienteId, next);
}

/** Conta leads ativos vinculados a um vendedor. Usado para decidir se o
 *  modal de delete precisa pedir reatribuição. */
export async function countLeadsByVendedor(
  clienteId: number,
  vendedorId: number,
): Promise<number> {
  const r = await db
    .select({ value: count() })
    .from(leads)
    .where(
      and(eq(leads.clienteId, clienteId), eq(leads.vendedorId, vendedorId)),
    );
  return r[0]?.value ?? 0;
}

/** Snapshot do vendedor para a coluna jsonb leads.vendedor. Remove senha. */
function vendedorSnapshot(v: Vendedor): Vendedor {
  const { senha: _senha, ...rest } = v;
  return { ...rest, senha: null } as Vendedor;
}

/** Atribui ou libera vendedor em um lead específico. Grava ID + snapshot. */
export async function setLeadVendedor(
  clienteId: number,
  leadId: number,
  vendedorId: number | null,
) {
  let snapshot: Vendedor | null = null;
  if (vendedorId !== null) {
    const vendedores = await loadVendedores(clienteId);
    const v = vendedores.find((x) => x.id === vendedorId);
    if (!v) throw new Error("Vendedor não encontrado.");
    snapshot = vendedorSnapshot(v);
  }
  await db
    .update(leads)
    .set({ vendedorId, vendedor: snapshot })
    .where(and(eq(leads.id, leadId), eq(leads.clienteId, clienteId)));
}

/** Sincroniza o snapshot vendedor em todos os leads que têm vendedor_id
 *  apontando pra esse usuário. Usado após editar dados do vendedor. */
export async function syncLeadsVendedorSnapshot(
  clienteId: number,
  vendedorId: number,
) {
  const vendedores = await loadVendedores(clienteId);
  const v = vendedores.find((x) => x.id === vendedorId);
  if (!v) {
    // Vendedor não existe mais — limpa snapshot.
    await db
      .update(leads)
      .set({ vendedor: null })
      .where(
        and(eq(leads.clienteId, clienteId), eq(leads.vendedorId, vendedorId)),
      );
    return;
  }
  await db
    .update(leads)
    .set({ vendedor: vendedorSnapshot(v) })
    .where(
      and(eq(leads.clienteId, clienteId), eq(leads.vendedorId, vendedorId)),
    );
}

