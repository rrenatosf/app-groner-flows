export async function createUsuario(
  clienteId: number,
  data: {
    nome: string;
    email: string;
    senha: string;
    telefone?: string | null;
    crmId?: string | null;
    role?: "owner" | "vendedor";
    recebeAgendamento?: boolean;
    horarios?: HorariosVendedor;
  },
) {
  const vendedores = await loadVendedores(clienteId);
  const emailLower = data.email.toLowerCase();
  if (
    vendedores.some(
      (v) => (v.email ?? "").toLowerCase() === emailLower,
    )
  ) {
    throw new Error("E-mail já cadastrado neste tenant.");
  }
  const hash = await bcrypt.hash(data.senha, 10);
  const novo: Vendedor = {
    id: nextVendedorId(vendedores),
    uid: crypto.randomUUID(),
    loja_ids: [],
    nome: data.nome,
    email: emailLower,
    senha: hash,
    telefone: data.telefone ?? null,
    crm_id: data.crmId ?? null,
    role: data.role ?? "vendedor",
    is_active: true,
    recebe_agendamento: data.recebeAgendamento ?? true,
    ultimo_agendamento: null,
    horarios: data.horarios ?? {},
    created_at: new Date().toISOString(),
  };
  await saveVendedores(clienteId, [...vendedores, novo]);
}

