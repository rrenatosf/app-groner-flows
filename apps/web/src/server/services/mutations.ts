export async function createAgente(
  clienteId: number,
  data: {
    name: string;
    description?: string | null;
    prompt?: string | null;
    debounceTime?: number;
    maxFollowups?: number;
    humanIntervention?: boolean;
    isActive?: boolean;
    voiceGender?: string | null;
    idN8n?: string | null;
  },
): Promise<number> {
  const trimmed = data.name.trim();
  if (!trimmed) throw new Error("Nome do agente é obrigatório.");

  // Confirma que o cliente existe — agente órfão não faz sentido.
  const cli = await db
    .select({ id: clientes.id })
    .from(clientes)
    .where(eq(clientes.id, clienteId))
    .limit(1);
  if (cli.length === 0) throw new Error("Cliente alvo não encontrado.");

  // `agentes.id` é GENERATED ALWAYS AS IDENTITY no banco — proibido
  // passar id explícito. Postgres gera; usamos RETURNING pra recuperar.
  const inserted = await db
    .insert(agentes)
    .values({
      name: trimmed,
      description: data.description ?? null,
      prompt: data.prompt ?? null,
      debounceTime: data.debounceTime ?? 10,
      maxFollowups: data.maxFollowups ?? 5,
      humanIntervention: data.humanIntervention ?? false,
      isActive: data.isActive ?? true,
      clienteId,
      idN8n: data.idN8n ?? null,
      voiceGender: data.voiceGender ?? null,
    })
    .returning({ id: agentes.id });
  if (!inserted[0]) throw new Error("Insert de agente não retornou id.");
  return inserted[0].id;
}

